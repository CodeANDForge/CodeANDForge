DEFAULT_REPLY = (
    "شكرًا لتواصلك معنا! لسه معنديش إجابة جاهزة لسؤالك ده. "
    "لو تحب تكلم أحد فريق الدعم مباشرة، اكتب 'أريد التحدث مع شخص' وهنحولك فورًا."
)

ESCALATION_TRIGGERS = ["شخص", "موظف", "دعم", "انسان", "إنسان", "احد", "أحد", "مسؤول"]


def get_bot_reply(user_message: str) -> str:
    message_lower = user_message.strip()
    for trigger in ESCALATION_TRIGGERS:
        if trigger in message_lower:
            return "ESCALATE"

    for keyword, reply in FAQ_KEYWORDS.items():
        if keyword in message_lower:
            return reply

    return DEFAULT_REPLY
